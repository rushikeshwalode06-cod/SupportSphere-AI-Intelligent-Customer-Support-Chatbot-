from sentence_transformers import SentenceTransformer
import numpy as np

EMBEDDING_MODEL_NAME = "sentence-transformers/all-MiniLM-L6-v2"

embedding_model = SentenceTransformer(
    EMBEDDING_MODEL_NAME
)

documents = df["document"].tolist()

embeddings = embedding_model.encode(
    documents,
    batch_size=64,
    show_progress_bar=True,
    convert_to_numpy=True,
    normalize_embeddings=True
)

embeddings = np.asarray(
    embeddings,
    dtype=np.float32
)

print("\nEmbeddings generated successfully!")
print("Number of documents:", len(embeddings))
print("Embedding dimensions:", embeddings.shape)

import faiss
import numpy as np

# Embedding dimensions
embedding_dimension = embeddings.shape[1]

# FAISS index using cosine similarity
index = faiss.IndexFlatIP(embedding_dimension)

# Add all document embeddings
index.add(embeddings)

print("FAISS vector database created successfully!")
print("Total indexed documents:", index.ntotal)
print("Vector dimensions:", embedding_dimension)

def retrieve_documents(query, top_k=4):

    query_embedding = embedding_model.encode(
        [query],
        convert_to_numpy=True,
        normalize_embeddings=True
    ).astype(np.float32)

    k = min(top_k, index.ntotal)

    scores, indices = index.search(
        query_embedding,
        k
    )

    results = []

    for score, idx in zip(scores[0], indices[0]):

        if idx < 0:
            continue

        row = df.iloc[int(idx)]

        results.append({
            "score": float(score),
            "question": row["instruction"],
            "answer": row["response"],
            "category": row["category"],
            "intent": row["intent"],
            "document": row["document"]
        })

    return results


