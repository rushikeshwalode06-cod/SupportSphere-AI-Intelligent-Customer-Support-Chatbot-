def generate_answer(query, top_k=4):
    query = query.strip()

    if not query:
        return {
            "answer": "Please enter a customer support question.",
            "sources": []
        }

    results = retrieve_documents(query, top_k=top_k)

    if not results:
        return {
            "answer": "No relevant information was found.",
            "sources": []
        }

    context = "\n\n".join(
        [
            f"Reference {i}:\n{item['document']}"
            for i, item in enumerate(results, start=1)
        ]
    )

    prompt = f"""
You are a helpful customer support assistant.

Answer the customer using only the reference information.
Be polite and concise.
Do not invent company policies or facts.
If the information is insufficient, say that you cannot
confirm the answer from the available knowledge base.

Reference information:
{context}

Customer question:
{query}

Answer:
"""

    inputs = tokenizer(
        prompt,
        return_tensors="pt",
        truncation=True,
        max_length=512
    ).to(device)

    with torch.inference_mode():
        output = generation_model.generate(
            **inputs,
            max_new_tokens=120,
            num_beams=2,
            do_sample=False
        )

    answer = tokenizer.decode(
        output[0],
        skip_special_tokens=True
    ).strip()

    sources = [
        {
            "category": item["category"],
            "question": item["question"],
            "reference_answer": item["answer"],
            "similarity": round(item["score"], 4)
        }
        for item in results
    ]

    return {
        "answer": answer,
        "sources": sources
    }


